// Builds web/src/twin/styles/fonts.css (npm run fonts:css): self-hosted Inter (Latin) and
// Noto Sans SC / HK (Chinese), split by Unicode range so the page only downloads the slices it uses.
// HarmonyOS Sans was the first choice, but its licence (clause 2.2) forbids modifying the fonts,
// which rules out the subsetting a web page needs; Noto Sans is SIL OFL and ships pre-split.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "web/src/twin/styles/fonts.css");
// Traditional Chinese faces live in their own file, loaded only when 繁體中文 is selected.
const outputHk = resolve(root, "web/src/twin/styles/fonts-hk.css");
const publicFonts = resolve(root, "web/public/fonts");
const relativeModules = "../../../../node_modules";

// Inter (variable weight) for Latin text and numerals: copied to public/fonts so it can be preloaded.
const interCss = readFileSync(resolve(root, "node_modules/@fontsource-variable/inter/wght.css"), "utf8");
mkdirSync(publicFonts, { recursive: true });
const interBlocks = interCss.split("@font-face").slice(1)
  .map((block) => `@font-face${block.split("}")[0]}}`)
  .filter((block) => /inter-latin(-ext)?-wght-normal/.test(block))
  .map((block) => {
    const file = block.match(/files\/([^)]+\.woff2)/)[1];
    copyFileSync(resolve(root, "node_modules/@fontsource-variable/inter/files", file), resolve(publicFonts, file));
    return block.replace(/url\(\.\/files\/([^)]+)\)/, "url(/fonts/$1)").replace("font-family: 'Inter Variable'", "font-family: 'Inter'");
  });

// Noto Sans SC (Simplified) and HK (Traditional): woff2 only, weights 400 / 500 / 700.
const cjkBlocks = { "noto-sans-sc": [], "noto-sans-hk": [] };
for (const family of Object.keys(cjkBlocks)) {
  for (const weight of [400, 500, 700]) {
    const css = readFileSync(resolve(root, `node_modules/@fontsource/${family}/${weight}.css`), "utf8");
    for (const block of css.split("@font-face").slice(1)) {
      const body = block.split("}")[0];
      const woff2 = body.match(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\)/);
      if (!woff2) continue;
      cjkBlocks[family].push(`@font-face${body.replace(/src: [^;]+;/, `src: url(${relativeModules}/@fontsource/${family}/files/${woff2[1]}) format('woff2');`)}}`);
    }
  }
}

const header = "/* Generated by scripts/fonts-css.mjs (npm run fonts:css). Do not edit by hand. */\n/* Inter and Noto Sans: SIL Open Font License 1.1. */\n";
writeFileSync(output, `${header}${[...interBlocks, ...cjkBlocks["noto-sans-sc"]].join("\n")}\n`);
writeFileSync(outputHk, `${header}${cjkBlocks["noto-sans-hk"].join("\n")}\n`);
console.log(`fonts.css: ${interBlocks.length} Inter + ${cjkBlocks["noto-sans-sc"].length} Noto Sans SC faces; fonts-hk.css: ${cjkBlocks["noto-sans-hk"].length} Noto Sans HK faces`);
